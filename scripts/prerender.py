"""Render template.html into a static index.html with headless Chrome.

script.js builds every section from data/*.json. Running it once here means visitors,
search engines and link previews get the full content in plain HTML; in the browser
script.js runs again over it to wire up the interactive bits.

Usage: python3 scripts/prerender.py   (needs Google Chrome or Chromium)
"""
import functools
import http.server
import os
import shutil
import subprocess
import sys
import threading
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Strings that only exist once script.js has rendered from the JSON data
MARKERS = ['class="pub"', 'class="repo-meta"', '<span>h-index</span>', 'class="card"']


class QuietHandler(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *args):
        pass


def find_chrome():
    for name in (os.environ.get("CHROME"), "google-chrome", "google-chrome-stable", "chromium", "chromium-browser"):
        if name and shutil.which(name):
            return shutil.which(name)
    sys.exit("prerender: Chrome/Chromium not found (set CHROME=/path/to/chrome)")


def main():
    handler = functools.partial(QuietHandler, directory=str(ROOT))
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    url = f"http://127.0.0.1:{server.server_port}/template.html?prerender"

    cmd = [find_chrome(), "--headless=new", "--disable-gpu", "--hide-scrollbars",
           "--virtual-time-budget=15000", "--dump-dom", url]
    if os.environ.get("CI"):
        cmd.insert(1, "--no-sandbox")
    dom = subprocess.run(cmd, capture_output=True, text=True, timeout=120, check=True).stdout
    server.shutdown()

    missing = [m for m in MARKERS if m not in dom]
    if missing:
        sys.exit(f"prerender: page did not render (missing {missing}); index.html left unchanged")
    # Drop the empty class="" left on <html> once script.js removes "js"
    dom = dom.strip().replace('<html lang="en" class="">', '<html lang="en">', 1)
    dom = dom.replace("<!-- Source page: scripts/prerender.py renders it into index.html. Edit this file, not index.html. -->",
                      "<!-- Generated by scripts/prerender.py from template.html. Do not edit by hand. -->", 1)
    (ROOT / "index.html").write_text(dom + "\n", encoding="utf-8")
    print(f"prerender: wrote index.html ({len(dom) // 1024} KB)")


if __name__ == "__main__":
    main()
